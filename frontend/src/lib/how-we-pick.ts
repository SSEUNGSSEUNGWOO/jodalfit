export type Step = { k: string; n: string; sub: string; d: string };
export type Factor = { t: string; v: string; d?: string };

export const POOL = 200; // ResultsView 의 candidate_pool — 바꾸면 여기도 바꾼다

export function steps(active: number): Step[] {
  const nf = new Intl.NumberFormat("ko-KR");
  return [
    {
      k: "지금 입찰 가능한 공고",
      n: nf.format(active),
      sub: "마감 90일 이내 · 참가자격 등록이 안 지난 것",
      d: "여기서 시작합니다. 글의 뜻이 비슷한 공고, 회사 등록업종을 허용하는 공고, 회사 공급물품 분류가 맞는 공고 세 통로로 후보를 모읍니다.",
    },
    {
      k: "비슷한 순서로 추린 공고",
      n: nf.format(POOL),
      sub: `전체의 ${((POOL / Math.max(1, active)) * 100).toFixed(1)}%`,
      d: "회사 등록업종·공급물품·수주 이력으로 만든 회사 벡터와 공고를 견줘 비슷한 순서로 추립니다.",
    },
    {
      k: "참가 자격 통과",
      n: "회사마다",
      sub: "면허·지역·등록 마감 대조",
      d: "면허(허용업종)·지역 제한(시·도 또는 시·군·구)·참가자격 등록 마감을 대조해 낼 수 없는 공고는 뺍니다.",
    },
    {
      k: "검토할 공고",
      n: "20",
      sub: "점수 순 · 다양성 반영",
      d: "아래 점수표로 줄 세우고, 비슷한 공고가 상위를 독점하지 않게 섞은 뒤 보여줍니다.",
    },
  ];
}

